def detect_single_lfa(
    model,
    data
):
    test_lfa_indices = torch.where(
        data.test_mask
        & (data.y == 1)
    )[0]

    if len(test_lfa_indices) == 0:
        print("\nNo LFA sample found.")
        return

    sample_index = int(
        test_lfa_indices[0].item()
    )

    model.eval()

    with torch.no_grad():
        output = model(
            data.x,
            data.edge_index
        )

        probabilities = torch.softmax(
            output,
            dim=1
        )

    predicted_class = int(
        probabilities[
            sample_index
        ].argmax().item()
    )

    lfa_probability = float(
        probabilities[
            sample_index,
            1
        ].item()
    )

    predicted_confidence = float(
        probabilities[
            sample_index,
            predicted_class
        ].item()
    )

    print("\nSingle Flow Detection:")
    print("Actual Class: LFA Attack")

    if predicted_class == 1:
        print("Result      : LFA Detected")
    else:
        print("Result      : No LFA")

    print(
        f"Confidence  : "
        f"{predicted_confidence * 100:.2f}%"
    )

    print(
        f"LFA Probability: "
        f"{lfa_probability * 100:.2f}%"
    )


