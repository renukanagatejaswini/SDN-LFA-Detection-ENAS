def connect_group(node_indices, edge_set):
    node_indices = list(node_indices)

    if len(node_indices) < 2:
        return

    if len(node_indices) > MAX_FLOWS_PER_IP:
        rng = np.random.default_rng(RANDOM_STATE)

        node_indices = rng.choice(
            node_indices,
            size=MAX_FLOWS_PER_IP,
            replace=False
        ).tolist()

    # Chain connections prevent fully-connected graph explosion
    for index in range(len(node_indices) - 1):
        first_node = int(node_indices[index])
        second_node = int(node_indices[index + 1])

        edge_set.add((first_node, second_node))
        edge_set.add((second_node, first_node))

    # Add skip connections
    for index in range(len(node_indices) - 2):
        first_node = int(node_indices[index])
        third_node = int(node_indices[index + 2])

        edge_set.add((first_node, third_node))
        edge_set.add((third_node, first_node))


def create_edge_index(df):
    print("\nCreating graph connections...")

    edge_set = set()

    source_groups = df.groupby(
        SOURCE_IP_COLUMN
    ).indices

    destination_groups = df.groupby(
        DESTINATION_IP_COLUMN
    ).indices

    for node_indices in source_groups.values():
        connect_group(node_indices, edge_set)

    for node_indices in destination_groups.values():
        connect_group(node_indices, edge_set)

    # Connect source IP flows with destination IP flows
    source_ip_nodes = source_groups
    destination_ip_nodes = destination_groups

    common_ips = set(source_ip_nodes.keys()).intersection(
        destination_ip_nodes.keys()
    )

    rng = np.random.default_rng(RANDOM_STATE)

    for ip_address in common_ips:
        source_nodes = list(
            source_ip_nodes[ip_address]
        )

        destination_nodes = list(
            destination_ip_nodes[ip_address]
        )

        if len(source_nodes) > 10:
            source_nodes = rng.choice(
                source_nodes,
                size=10,
                replace=False
            ).tolist()

        if len(destination_nodes) > 10:
            destination_nodes = rng.choice(
                destination_nodes,
                size=10,
                replace=False
            ).tolist()

        pair_count = min(
            len(source_nodes),
            len(destination_nodes)
        )

        for index in range(pair_count):
            first_node = int(source_nodes[index])
            second_node = int(destination_nodes[index])

            if first_node != second_node:
                edge_set.add(
                    (first_node, second_node)
                )
                edge_set.add(
                    (second_node, first_node)
                )

    # Isolated nodes kosam self loops
    connected_nodes = set()

    for source_node, destination_node in edge_set:
        connected_nodes.add(source_node)
        connected_nodes.add(destination_node)

    for node_index in range(len(df)):
        if node_index not in connected_nodes:
            edge_set.add(
                (node_index, node_index)
            )

    edge_array = np.array(
        list(edge_set),
        dtype=np.int64
    ).T

    edge_index = torch.tensor(
        edge_array,
        dtype=torch.long
    )

    print("Total nodes:", len(df))
    print("Total directed edges:", edge_index.shape[1])

    return edge_index


