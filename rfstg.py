def evaluate_model(model, data):
    model.eval()

    with torch.no_grad():
        output = model(
            data.x,
            data.edge_index
        )

        probabilities = torch.softmax(
            output,
            dim=1
        )

        predictions = output.argmax(dim=1)

    y_true = (
        data.y[data.test_mask]
        .cpu()
        .numpy()
    )

    y_pred = (
        predictions[data.test_mask]
        .cpu()
        .numpy()
    )

    y_probability = (
        probabilities[
            data.test_mask,
            1
        ]
        .cpu()
        .numpy()
    )

    accuracy = accuracy_score(
        y_true,
        y_pred
    )

    precision = precision_score(
        y_true,
        y_pred,
        zero_division=0
    )

