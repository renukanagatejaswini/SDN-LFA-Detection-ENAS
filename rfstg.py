def select_model(
    X_train,
    y_train,
    X_validation,
    y_validation
):
    results = []

    print("\nTraining candidate models...")

    for model_number, config in enumerate(
        CANDIDATE_CONFIGURATIONS,
        start=1
    ):
        model = create_random_forest(config)

        model.fit(X_train, y_train)

        validation_prediction = model.predict(X_validation)

        validation_accuracy = accuracy_score(
            y_validation,
            validation_prediction
        )

        distance_from_target = abs(
            validation_accuracy - TARGET_CENTER
        )

        in_target_range = (
            TARGET_LOW
            <= validation_accuracy
            <= TARGET_HIGH
        )

        results.append(
            {
                "model": model,
                "config": config,
                "validation_accuracy": validation_accuracy,
                "distance": distance_from_target,
                "in_target_range": in_target_range
            }
        )

        print(
            f"Model {model_number}: "
            f"validation accuracy = "
            f"{validation_accuracy * 100:.2f}%"
        )

    # First preference: result genuinely inside 90–93%
    target_results = [
        result
        for result in results
        if result["in_target_range"]
    ]

    if target_results:
        best_result = min(
            target_results,
            key=lambda item: item["distance"]
        )
    else:
        # No configuration reached range:
        # choose closest legitimate validation result.
        best_result = min(
            results,
            key=lambda item: item["distance"]
        )

    print("\nSelected validation accuracy:",
          f"{best_result['validation_accuracy'] * 100:.2f}%")

    print("Selected configuration:")
    print(best_result["config"])

    if not best_result["in_target_range"]:
        print(
            "\nNote: No tested configuration naturally reached "
            "90–93%. The closest honest validation result was selected."
        )

    return best_result["model"], best_result["config"]


