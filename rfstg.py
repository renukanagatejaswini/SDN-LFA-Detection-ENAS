def prepare_graph_data(df):
    feature_values = df[
        FEATURE_COLUMNS
    ].to_numpy(dtype=np.float32)

    labels = df[
        LABEL_COLUMN
    ].to_numpy(dtype=np.int64)

    train_mask, validation_mask, test_mask = (
        create_masks(labels)
    )

    scaler = StandardScaler()

    # Train nodes meeda matrame scaler fit
    scaler.fit(
        feature_values[
            train_mask.numpy()
        ]
    )

    scaled_features = scaler.transform(
        feature_values
    ).astype(np.float32)

    edge_index = create_edge_index(df)

    graph_data = Data(
        x=torch.tensor(
            scaled_features,
            dtype=torch.float32
        ),
        edge_index=edge_index,
        y=torch.tensor(
            labels,
            dtype=torch.long
        ),
        train_mask=train_mask,
        val_mask=validation_mask,
        test_mask=test_mask
    )

    return graph_data, scaler


